@app.cell
def _(df, go, np, plot_type):


    # Get column names (handle variations)
    wl_col = [col for col in df.columns if 'nm' in col.lower()][0]
    t_col = [col for col in df.columns if '%t' in col.lower() or 't' in col.lower()][0]

    df_sorted = df.sort_values(by=wl_col)
    wavelength = df_sorted[wl_col].values
    transmittance = df_sorted[t_col].values

    if plot_type.value == "Transmittance (%T)":
        y_data = transmittance
        y_label = "Transmittance (%T)"
        title = "UV-Vis Spectrum - Transmittance"
    else:
        # Convert transmittance to absorbance: A = -log10(%T/100)
        y_data = -np.log10(transmittance / 100)
        y_label = "Absorbance (A)"
        title = "UV-Vis Spectrum - Absorbance"

    # Calculate photon energy in eV from wavelength in nm
    # E (eV) = 1239.84 / λ (nm)
    energy_ev = 1239.84 / wavelength

    fig = go.Figure()
    fig.add_trace(go.Scatter(
        x=wavelength,
        y=y_data,
        mode='lines',
        name='UV-Vis',
        line=dict(color='#1f77b4', width=2)
    ))

    # Get energy range for the secondary axis
    energy_min = energy_ev.min()
    energy_max = energy_ev.max()
    wl_min = wavelength.min()
    wl_max = wavelength.max()

    fig.update_layout(
        title=title,
        xaxis=dict(
            title="Wavelength (nm)",
            autorange="reversed"
        ),
        # Secondary x-axis for energy
        xaxis2=dict(
            title="Photon Energy (eV)",
            overlaying="x",
            side="top",
            range=[energy_max, energy_min],  # Reversed like wavelength
            tickmode='linear',
            tick0=energy_min,
            dtick=(energy_max - energy_min) / 5  # ~5 ticks
        ),
        yaxis_title=y_label,
        template='plotly_white',
        hovermode='x unified',
        width=900,
        height=700,
        font=dict(size=12),
        margin=dict(t=100)
    )
    return energy_ev, transmittance, wavelength


