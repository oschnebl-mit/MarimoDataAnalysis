@app.cell
def _(StringIO, data_input, pd):
    # Parse the data
    raw_data = data_input.value
    lines = raw_data.strip().split('\n')

    # Skip header lines until we find the column names
    header_idx = 0
    for i, line in enumerate(lines):
        if 'nm' in line.lower():
            header_idx = i
            break

    # Reconstruct CSV starting from header
    csv_data = '\n'.join(lines[header_idx:])

    try:
        df = pd.read_csv(StringIO(csv_data))
        df.columns = df.columns.str.strip()  # Remove whitespace
        success = True
        error_msg = None
    except Exception as e:
        success = False
        error_msg = str(e)
        df = None
    return df, error_msg, success


